  static ImageFilterSpec getFilterByName(String name) {
    final cleanName = name.trim().toLowerCase();
    return availableFilters.firstWhere(
      (f) =>
          f.name.toLowerCase() == cleanName ||
          (cleanName == 'b&w' && f.name == 'Black & White') ||
          (cleanName == 'mono' && f.name == 'Black & White'),
      orElse: () => availableFilters.first,
    );
  }

  static List<double>? getMatrixByName(String name) {
    final spec = getFilterByName(name);
    if (spec.name == 'Normal') return null;
    return spec.matrix;
  }

  /// Asynchronously applies the selected filter matrix to an image file
  /// in a separate isolate using [compute].
  /// Returns path to processed temporary file or original path if Normal / Error.
  static Future<String> processImageWithFilter({
    required String inputPath,
    required String filterName,
  }) async {
    final spec = getFilterByName(filterName);
    if (spec.name == 'Normal') {
      return inputPath;
    }

    final file = File(inputPath);
    if (!file.existsSync()) {
      return inputPath;
    }

    try {
      final param = _FilterWorkerParam(
        inputPath: inputPath,
        matrix: spec.matrix,
      );
      final outputPath = await compute(_filterIsolateWorker, param);
      return outputPath ?? inputPath;
    } catch (e) {
      debugPrint('Error applying filter to image: $e');
      return inputPath;
    }
  }
}

class _FilterWorkerParam {
  final String inputPath;
  final List<double> matrix;

  _FilterWorkerParam({required this.inputPath, required this.matrix});
}

String? _filterIsolateWorker(_FilterWorkerParam param) {
  final file = File(param.inputPath);
  if (!file.existsSync()) return null;

  final bytes = file.readAsBytesSync();
  final image = img.decodeImage(bytes);
  if (image == null) return null;

  final m = param.matrix;

  for (final pixel in image) {
    final r = pixel.r;
    final g = pixel.g;
    final b = pixel.b;
    final a = pixel.a;

    final nr = (r * m[0] + g * m[1] + b * m[2] + a * m[3] + m[4]).clamp(0, 255);
    final ng = (r * m[5] + g * m[6] + b * m[7] + a * m[8] + m[9]).clamp(0, 255);
    final nb = (r * m[10] + g * m[11] + b * m[12] + a * m[13] + m[14]).clamp(
      0,
      255,
    );
    final na = (r * m[15] + g * m[16] + b * m[17] + a * m[18] + m[19]).clamp(
      0,
      255,
    );

    pixel.r = nr;
    pixel.g = ng;
    pixel.b = nb;
    pixel.a = na;
  }

  final encoded = img.encodeJpg(image, quality: 88);
  final tempDir = Directory.systemTemp;
  final tempPath =
      '${tempDir.path}/momento_filtered_${DateTime.now().millisecondsSinceEpoch}.jpg';
  final outputFile = File(tempPath);
  outputFile.writeAsBytesSync(encoded);

  return tempPath;
}
